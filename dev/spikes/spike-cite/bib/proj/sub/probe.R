probe <- function(tag) {
  out <- character()
  add <- function(...) out <<- c(out, paste0(...))
  add("== ", tag)
  add("getwd: ", getwd())
  add("current_input(dir=TRUE): ", tryCatch(knitr::current_input(dir=TRUE), error=function(e) "ERR"))
  md <- tryCatch(rmarkdown::metadata, error=function(e) NULL)
  add("rmarkdown::metadata class/len: ", paste(class(md), collapse="/"), " ", length(md), " names: ", paste(names(md), collapse=","))
  add("rmarkdown::metadata$bibliography: ", paste(deparse(md$bibliography), collapse=""))
  fm <- tryCatch(rmarkdown::yaml_front_matter(knitr::current_input(dir=TRUE)), error=function(e) NULL)
  add("yaml_front_matter$bibliography: ", paste(deparse(fm$bibliography), collapse=""))
  add("yaml_front_matter has references: ", !is.null(fm$references))
  ev <- Sys.getenv(); q <- ev[grepl("^QUARTO|^RMARKDOWN|^RSTUDIO|^PANDOC", names(ev))]
  add("env: ", paste(names(q), "=", substr(q,1,80), collapse=" | "))
  ei <- Sys.getenv("QUARTO_EXECUTE_INFO")
  if (nzchar(ei) && file.exists(ei)) {
    j <- jsonlite::read_json(ei)
    add("EXECUTE_INFO top names: ", paste(names(j), collapse=","))
    add("EXECUTE_INFO format$pandoc names: ", paste(names(j$format$pandoc), collapse=","))
    add("EXECUTE_INFO format$metadata names: ", paste(names(j$format$metadata), collapse=","))
    add("EXECUTE_INFO bibliography (format$pandoc): ", paste(deparse(j$format$pandoc$bibliography), collapse=""))
    add("EXECUTE_INFO bibliography (format$metadata): ", paste(deparse(j$format$metadata$bibliography), collapse=""))
    add("EXECUTE_INFO project-dir: ", paste(deparse(j[["project-dir"]]), collapse=""))
    add("EXECUTE_INFO sourceFile: ", paste(deparse(j$sourceFile), collapse=""))
    add("EXECUTE_INFO keys with biblio anywhere: ", paste(grep("bib|csl|references", unlist(rapply(j, function(x) 1, how="list") |> names()), value=TRUE), collapse=","))
    writeLines(readLines(ei, warn=FALSE), paste0("execinfo_", tag, ".json"))
  } else add("no QUARTO_EXECUTE_INFO")
  writeLines(out, paste0("probe_", tag, ".txt"))
}
