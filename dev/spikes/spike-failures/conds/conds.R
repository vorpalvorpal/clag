cap <- function(id, expr, ...) {
  ex <- substitute(expr)
  withCallingHandlers(
    tryCatch(eval(ex, parent.frame()), error = function(e) out[[length(out) + 1L]] <<- data.frame(id = id, kind = "error", text = conditionMessage(e))),
    warning = function(w) { out[[length(out) + 1L]] <<- data.frame(id = id, kind = "warning", text = conditionMessage(w)); invokeRestart("muffleWarning") },
    message = function(m) { out[[length(out) + 1L]] <<- data.frame(id = id, kind = "message", text = sub("\n$", "", conditionMessage(m))); invokeRestart("muffleMessage") })
  invisible()
}
